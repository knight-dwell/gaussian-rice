#!/usr/bin/env python3
"""gen-popup-mode.py: write ~/.config/i3/popup-mode.conf (included by the i3 config).

While an eww popup is open, i3 is in mode "eww-popup" so that Escape can close
the popup. i3 ignores normal bindings inside a mode, so this script copies
every normal-mode binding into that mode:
  * popup keys (popup.sh toggle ...) are copied as they are: they already
    switch/close popups themselves
  * every other key first closes the popup, then does its usual job
Escape closes the popup. Run it again after adding or changing bindings:
    ~/.config/i3/scripts/gen-popup-mode.py && i3-msg reload
"""
import os
import re

CONFIG = os.path.expanduser("~/.config/i3/config")
OUT = os.path.expanduser("~/.config/i3/popup-mode.conf")
CLOSE = "exec --no-startup-id ~/.config/eww/scripts/popup/popup.sh close"

lines, depth = [], 0
for raw in open(CONFIG, encoding="utf-8"):
    line = raw.strip()
    if re.match(r'mode\s+"[^"]+"\s*\{', line):
        depth += 1
        continue
    if line == "}" and depth:
        depth -= 1
        continue
    if depth or not re.match(r"bind(sym|code)\s", line):
        continue
    toks = line.split()
    flags, i = [], 1
    while toks[i].startswith("--"):
        flags.append(toks[i])
        i += 1
    key = toks[i]
    i += 1
    while i < len(toks) and (key.endswith("+") or toks[i].startswith("+")):
        key += toks[i]
        i += 1
    cmd = " ".join(toks[i:])
    if key in ("Escape",):
        continue
    if "popup.sh" in cmd:
        new = cmd
    else:
        new = f"{CLOSE}; {cmd}"
    lines.append(f"\tbindsym {' '.join(flags + [key])} {new}")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("# GENERATED by ~/.config/i3/scripts/gen-popup-mode.py: do not edit by hand.\n")
    fh.write("# While a bar popup is open: Escape closes it, every normal shortcut still works\n")
    fh.write("# (it closes the popup first).\n")
    fh.write('mode "eww-popup" {\n')
    fh.write(f"\tbindsym Escape {CLOSE}\n")
    fh.write("\n".join(lines) + "\n}\n")
print(f"{OUT}: {len(lines)} shortcuts")

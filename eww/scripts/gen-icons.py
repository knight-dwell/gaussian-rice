#!/usr/bin/env python3
"""Resolve Nerd Font glyph *names* to characters for the bar.

Reads  ~/.config/eww/icons.json       (key -> glyph name, used as {ic.key} in yuck)
       ~/.config/eww/workspaces.json  (workspace number -> glyph name + label)
Writes ~/.config/eww/generated/icons.yuck       (defvar ic '{...}')
       ~/.config/eww/generated/workspaces.json  (resolved, read by workspaces-listen.py)
"""
import glob
import json
import os
import sys

from fontTools.ttLib import TTFont

EWW = os.path.expanduser("~/.config/eww")
FONT = glob.glob(os.path.expanduser("~/.local/share/fonts/JetBrainsMonoNerd/JetBrainsMonoNerdFont-Regular.ttf"))[0]


def main():
    glyphs = {name: chr(cp) for cp, name in TTFont(FONT).getBestCmap().items()}

    def resolve(name, where):
        if name not in glyphs:
            sys.exit("gen-icons: unknown glyph name '{}' in {}".format(name, where))
        return glyphs[name]

    icons = json.load(open(os.path.join(EWW, "icons.json")))
    ic = {k: resolve(v, "icons.json") for k, v in icons.items() if not k.startswith("_")}

    ws = json.load(open(os.path.join(EWW, "workspaces.json")))
    wsout = {k: {"icon": resolve(v["icon"], "workspaces.json"), "label": v.get("label", "")}
             for k, v in ws.items() if not k.startswith("_")}

    os.makedirs(os.path.join(EWW, "generated"), exist_ok=True)
    with open(os.path.join(EWW, "generated", "icons.yuck"), "w") as fh:
        fh.write(";; GENERATED by scripts/gen-icons.py from icons.json: do not edit\n")
        fh.write("(defvar ic '{}')\n".format(json.dumps(ic, ensure_ascii=False)))
        # level-indexed arrays: ic_bat[0..10] (by capacity/10), ic_wifi[0..4] (by signal level)
        bat = [ic["bat_empty"]] + [ic["bat_%d" % (i * 10)] for i in range(1, 10)] + [ic["bat_full"]]
        wifi = [ic["wifi_%d" % i] for i in range(5)]
        fh.write("(defvar ic_bat '{}')\n".format(json.dumps(bat, ensure_ascii=False)))
        fh.write("(defvar ic_wifi '{}')\n".format(json.dumps(wifi, ensure_ascii=False)))
    with open(os.path.join(EWW, "generated", "workspaces.json"), "w") as fh:
        json.dump(wsout, fh, ensure_ascii=False)
    print("gen-icons: {} icons, {} workspaces".format(len(ic), len(wsout)))


if __name__ == "__main__":
    main()
